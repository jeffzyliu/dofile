// Writes src/app/sample-files.ts from the sample project's files (web/sample/: analysis.do, helpers.do, data/wages.dta),
// so the page has them in its own bundle and "Restore the sample" works offline. `npm run sample` runs this; a test
// (test/sample.test.ts) fails when the module is not what this makes. The data file is made by sample/make_sample.py.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const FILES = ["analysis.do", "helpers.do", "data/wages.dta"];
const dir = fileURLToPath(new URL("../sample/", import.meta.url));

/** The module's text. Text files as strings, the .dta as base64. */
export function moduleText(): string {
  const entries = FILES.map((path) => {
    const bytes = readFileSync(`${dir}/${path}`);
    return path.endsWith(".dta")
      ? `  { path: ${JSON.stringify(path)}, base64: ${JSON.stringify(bytes.toString("base64"))} },`
      : `  { path: ${JSON.stringify(path)}, text: ${JSON.stringify(bytes.toString("utf8"))} },`;
  });
  return `// GENERATED by scripts/make-sample.ts (npm run sample) from web/sample/. Do not edit.
export const SAMPLE: { path: string; text?: string; base64?: string }[] = [
${entries.join("\n")}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(fileURLToPath(new URL("../src/app/sample-files.ts", import.meta.url)), moduleText());
  console.log("wrote src/app/sample-files.ts");
}
